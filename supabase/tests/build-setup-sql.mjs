// Regenerates supabase/SQL_EDITOR_SETUP.sql = every migration (in order) + seed.
//   node supabase/tests/build-setup-sql.mjs          write the file
//   node supabase/tests/build-setup-sql.mjs --check  exit 1 if it is stale
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SUPA = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(SUPA, 'SQL_EDITOR_SETUP.sql')

const HEADER = `-- =====================================================================
-- Campus Forge -> Supabase  Full Setup (single script for the SQL Editor)
-- =====================================================================
-- GENERATED by supabase/tests/build-setup-sql.mjs from supabase/migrations/*
-- + supabase/seed.sql. Do not edit by hand; add a migration and regenerate.
--
-- For a FRESH project only: paste all of this into the SQL Editor and run
-- once. (Migrations 00-10 use plain CREATE and are not re-runnable; on an
-- existing database apply only the new migration files instead.)
--
-- Afterwards:
--   * Auth -> Providers -> Email: enable email signups (confirmations optional)
--   * Edge Function secret QR_SIGNING_SECRET (>= 32 random chars), then deploy
--     claim, qr-catalog, admin-spawn
--   * promote your admin: update public.profiles set role = 'ADMIN' where email = '...';
--   * web-client env: VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY (publishable key)
--   * battle-engine env: SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY /
--     CAMPUSFORGE_CORS_ALLOWED_ORIGINS
`

export function buildSetupSql() {
  const migDir = join(SUPA, 'migrations')
  const parts = [HEADER]
  for (const f of readdirSync(migDir).filter((x) => x.endsWith('.sql')).sort()) {
    parts.push(`\n-- ******************** FILE: migrations/${f} ********************\n`)
    parts.push(readFileSync(join(migDir, f), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n')
  }
  parts.push('\n-- ******************** FILE: seed.sql (card catalog) ********************\n')
  parts.push(readFileSync(join(SUPA, 'seed.sql'), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n')
  return parts.join('')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = buildSetupSql()
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n')
    if (current !== next) {
      console.error('SQL_EDITOR_SETUP.sql is stale: run node supabase/tests/build-setup-sql.mjs')
      process.exit(1)
    }
    console.log('SQL_EDITOR_SETUP.sql is up to date')
  } else {
    writeFileSync(OUT, next)
    console.log(`wrote ${OUT}`)
  }
}
